# Stick font: em box 0..10 x 0..14 (y up). Each glyph is strokes of (x, y) points.
# Original geometry, not copied from Hershey / MADE Likes.

def _s(*strokes: str) -> list[list[tuple[float, float]]]:
    out: list[list[tuple[float, float]]] = []
    for stroke in strokes:
        pts = []
        for pair in stroke.split():
            x, y = pair.split(",")
            pts.append((float(x), float(y)))
        out.append(pts)
    return out


